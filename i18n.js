export function detectLang(search = '', navLang = 'en') {
  const q = new URLSearchParams(search).get('lang');
  if (q && messages[q]) return q;
  const n = (navLang || 'en').slice(0, 2).toLowerCase();
  return messages[n] ? n : 'en';
}
